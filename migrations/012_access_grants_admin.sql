-- 012: Admin access-grants panel (soft revoke, permission level, reason
-- visibility, last-accessed, expiry logging, grant event history).
--   access_grants.permission: 'full' (repo + PDF + AI retrieval, as before)
--       or 'read' (repo + PDF, excluded from AI retrieval). Default 'full'.
--   access_grants.reason_visible: FALSE hides the reason from non-admin APIs.
--   access_grants.revoked_at / revoked_by: soft revoke (row is kept for history).
--   access_grants.last_accessed_at: set (throttled) when a grant is the
--       deciding factor for a PDF open / RAG retrieval. NULL = never.
--   access_grants.expired_logged_at: set once the scheduler/backfill wrote the
--       'expired' event, so the event is emitted exactly once.
--   access_grant_events: append-only history (no FK on purpose: survives
--       grant / document deletion).
-- Additive and idempotent: safe to run more than once; never drops data.
-- Fresh installs: applied automatically (postgres mounts ./migrations at
--   /docker-entrypoint-initdb.d and runs files in lexicographic order).
-- Existing installs (REQUIRED before deploying the new backend):
--   psql "$DATABASE_URL" -f migrations/012_access_grants_admin.sql
--   or: Get-Content migrations\012_access_grants_admin.sql | docker exec -i legpro-postgres psql -U legpro -d legpro

ALTER TABLE access_grants ADD COLUMN IF NOT EXISTS permission        TEXT        NOT NULL DEFAULT 'full';
ALTER TABLE access_grants ADD COLUMN IF NOT EXISTS reason_visible    BOOLEAN     NOT NULL DEFAULT TRUE;
ALTER TABLE access_grants ADD COLUMN IF NOT EXISTS revoked_at        TIMESTAMPTZ;
ALTER TABLE access_grants ADD COLUMN IF NOT EXISTS revoked_by        TEXT;
ALTER TABLE access_grants ADD COLUMN IF NOT EXISTS last_accessed_at  TIMESTAMPTZ;
ALTER TABLE access_grants ADD COLUMN IF NOT EXISTS expired_logged_at TIMESTAMPTZ;

DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'access_grants_permission_chk') THEN
    ALTER TABLE access_grants ADD CONSTRAINT access_grants_permission_chk CHECK (permission IN ('full','read'));
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_access_grants_doc_id ON access_grants (doc_id);
CREATE INDEX IF NOT EXISTS idx_access_grants_active_exp ON access_grants (expires_at) WHERE revoked_at IS NULL;

CREATE TABLE IF NOT EXISTS access_grant_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grant_id     TEXT        NOT NULL,   -- no FK: survives doc/grant deletion
    event_type   TEXT        NOT NULL,   -- granted|revoked|expired|extended|expiry_set|expiry_cleared|permission_changed|visibility_changed|reason_revealed
    actor_id     TEXT,                   -- NULL = system
    actor_name   TEXT,
    granted_to   TEXT,
    grantee_name TEXT,
    doc_id       TEXT,
    doc_title    TEXT,
    old_value    TEXT,
    new_value    TEXT,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_age_created ON access_grant_events (created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_age_grant   ON access_grant_events (grant_id);

-- Backfill 1: one 'granted' event per existing grant (guarded, re-runnable).
INSERT INTO access_grant_events
    (grant_id, event_type, actor_id, actor_name, granted_to, grantee_name, doc_id, doc_title, created_at)
SELECT ag.id, 'granted', ag.granted_by, gb.username, ag.granted_to, ru.username,
       ag.doc_id, r.judul, COALESCE(ag.created_at, now())
FROM access_grants ag
LEFT JOIN users gb ON gb.id = ag.granted_by
LEFT JOIN users ru ON ru.id = ag.granted_to
LEFT JOIN regulations r ON ag.doc_id = r.id::text
WHERE NOT EXISTS (SELECT 1 FROM access_grant_events e
                  WHERE e.grant_id = ag.id AND e.event_type = 'granted');

-- Backfill 2: one 'expired' event per already-expired grant. MUST run before
-- the UPDATE below (the UPDATE clears the expired_logged_at IS NULL condition).
INSERT INTO access_grant_events
    (grant_id, event_type, actor_id, actor_name, granted_to, grantee_name, doc_id, doc_title, created_at)
SELECT ag.id, 'expired', NULL, NULL, ag.granted_to, ru.username,
       ag.doc_id, r.judul, ag.expires_at
FROM access_grants ag
LEFT JOIN users ru ON ru.id = ag.granted_to
LEFT JOIN regulations r ON ag.doc_id = r.id::text
WHERE ag.revoked_at IS NULL AND ag.expires_at IS NOT NULL AND ag.expires_at < now()
  AND ag.expired_logged_at IS NULL
  AND NOT EXISTS (SELECT 1 FROM access_grant_events e
                  WHERE e.grant_id = ag.id AND e.event_type = 'expired');

-- Backfill 3: mark them logged so the first job run does not emit a flood.
UPDATE access_grants SET expired_logged_at = expires_at
WHERE revoked_at IS NULL AND expires_at IS NOT NULL AND expires_at < now()
  AND expired_logged_at IS NULL;
